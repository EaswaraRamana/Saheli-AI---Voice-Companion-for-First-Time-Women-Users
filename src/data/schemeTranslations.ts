export function getLocalizedStepTitle(schemeId: string, stepNum: number, lang: LanguageCode, fallback: string): string {
  const schemeSteps = SCHEME_STEPS_TRANSLATIONS[schemeId];
  if (schemeSteps && schemeSteps[stepNum] && schemeSteps[stepNum].title[lang]) {
    return schemeSteps[stepNum].title[lang];
  }
  return fallback;
}

export function getLocalizedStepDesc(schemeId: string, stepNum: number, lang: LanguageCode, fallback: string): string {
  const schemeSteps = SCHEME_STEPS_TRANSLATIONS[schemeId];
  if (schemeSteps && schemeSteps[stepNum] && schemeSteps[stepNum].desc[lang]) {
    return schemeSteps[stepNum].desc[lang];
  }
  return fallback;
}

export function getLocalizedSchemeField(
  schemeId: string,
  field: 'benefits' | 'eligibility' | 'whereToGo' | 'officerVoiceScript' | 'audioGreeting' | 'benefitBadge',
  lang: LanguageCode,
  originalValue: string
): string {
  const extra = SCHEME_EXTRA_TRANSLATIONS[schemeId];
  if (extra && extra[field] && (extra[field] as any)[lang]) {
    return (extra[field] as any)[lang];
  }
  return originalValue;
}
